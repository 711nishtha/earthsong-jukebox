/**
 * Extracts the "Hear the change" stills (moment A and B) from the shipped videos, driven by each
 * track's `compare` config, and writes a transparency report of the computed summaries.
 *
 *   npx vite-node scripts/build_compare.ts
 *
 * Outputs public/media/compare/<track>-a.webp, -b.webp and docs/hear-the-change.md.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { changes, snapshot } from '../src/audio/snapshot';
import type { FeatureTrack } from '../src/audio/render';
import { TRACKS } from '../src/tracks';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'public', 'media', 'compare');
mkdirSync(OUT, { recursive: true });

const doc: string[] = [
  '# Hear the change: computed summaries',
  '',
  'Generated by `npx vite-node scripts/build_compare.ts` from the precomputed features (the same numbers the app uses). Snapshots are the mean of each feature over the window; nothing here is typed by hand.',
  '',
];

for (const t of TRACKS.filter((x) => x.compare)) {
  const c = t.compare!;
  for (const [side, m] of [['a', c.a], ['b', c.b]] as const) {
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-ss', String(m.still), '-i', join(ROOT, 'public', t.video),
      '-frames:v', '1', '-vf', `${c.stillFilter ? `${c.stillFilter},` : ''}scale=1280:-2`, '-c:v', 'libwebp', '-quality', '78', join(OUT, `${t.id}-${side}.webp`)]);
  }
  const ft = JSON.parse(readFileSync(join(ROOT, 'public', 'features', `${t.id}.json`), 'utf8')) as FeatureTrack;
  const a = snapshot(ft, c.a.from, c.a.to), b = snapshot(ft, c.b.from, c.b.to);
  doc.push(`## ${t.title}: ${c.heading} (${c.kind === 'change' ? 'change over time' : 'seasonal, within one year'})`, '');
  doc.push(`Windows: A = ${c.a.label} (${c.a.from}–${c.a.to} s), B = ${c.b.label} (${c.b.from}–${c.b.to} s).`, '');
  doc.push(`> ${c.summary(a, b)}`, '', `Caveat: ${c.note}`, '');
  doc.push('| What changed (data mappings only) | A | B |', '|---|---|---|');
  for (const ch of changes(t.sound, a, b)) doc.push(`| ${ch.binding.visual} | ${ch.a.toFixed(4)} | ${ch.b.toFixed(4)} |`);
  doc.push('');
  console.log(`${t.id}: stills + summary written`);
}

doc.push('## Not compared', '', '- **Storm Drums:** the globe rotates, so how much lightning is on screen in a window depends on which side of Earth faces the camera as much as on the season. A seasonal comparison would be confounded, so we do not offer one.', '- **Forest Heights, Four Winds:** single periods (one year of GEDI data; six weeks of aerosols), so there is no meaningful before/after.', '');
writeFileSync(join(ROOT, 'docs', 'hear-the-change.md'), doc.join('\n'));
